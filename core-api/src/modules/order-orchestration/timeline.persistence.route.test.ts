import assert from "node:assert/strict";
import test from "node:test";

import { InMemoryDocumentStore } from "../../platform/persistence/in-memory-document-store.js";
import { createServer } from "../../server.js";

async function createAndAdvanceOrder(baseUrl: string): Promise<{ id: string }> {
  const createBasket = await fetch(`${baseUrl}/api/v1/consumer/baskets`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      consumerId: "consumer-timeline-persist-1",
      merchantId: "merchant-timeline-persist-1",
      currency: "USD",
    }),
  });
  const basket = (await createBasket.json()) as { id: string };

  await fetch(`${baseUrl}/api/v1/consumer/baskets/${basket.id}`, {
    method: "PATCH",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      items: [
        {
          itemId: "item-timeline-persist-1",
          name: "Burger",
          quantity: 1,
          unitPriceCents: 1299,
          modifiers: [],
        },
      ],
    }),
  });

  const quoteResponse = await fetch(`${baseUrl}/api/v1/consumer/quotes`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ basketId: basket.id }),
  });
  const quote = (await quoteResponse.json()) as {
    quoteId: string;
    quoteHash: string;
    basketId: string;
  };

  const checkoutResponse = await fetch(`${baseUrl}/api/v1/consumer/checkout`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      basketId: quote.basketId,
      quoteId: quote.quoteId,
      quoteHash: quote.quoteHash,
    }),
  });
  const checkout = (await checkoutResponse.json()) as {
    checkoutId: string;
    quoteHash: string;
  };

  const createOrderResponse = await fetch(`${baseUrl}/api/v1/consumer/orders`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      checkoutId: checkout.checkoutId,
      quoteHash: checkout.quoteHash,
    }),
  });
  const order = (await createOrderResponse.json()) as { id: string };

  await fetch(`${baseUrl}/api/v1/merchant/orders/${order.id}/accept`, { method: "POST" });
  await fetch(`${baseUrl}/internal/orders/${order.id}/request-dispatch`, { method: "POST" });

  return order;
}

test("order timeline survives core-api restart when persistence is enabled", async () => {
  const documentStore = new InMemoryDocumentStore();

  const appA = createServer({
    enablePersistence: true,
    documentStore,
  });
  const listenerA = appA.listen(0);

  let orderId: string;
  try {
    const address = listenerA.address();
    if (!address || typeof address === "string") {
      throw new Error("Failed to bind test listener");
    }

    const baseUrl = `http://127.0.0.1:${address.port}`;
    const order = await createAndAdvanceOrder(baseUrl);
    orderId = order.id;

    const timeline = await fetch(`${baseUrl}/api/v1/consumer/orders/${order.id}/timeline`);
    assert.equal(timeline.status, 200);
    const payload = (await timeline.json()) as { entries: unknown[] };
    assert.ok(payload.entries.length >= 3);
  } finally {
    listenerA.close();
  }

  const appB = createServer({
    enablePersistence: true,
    documentStore,
  });
  const listenerB = appB.listen(0);

  try {
    const address = listenerB.address();
    if (!address || typeof address === "string") {
      throw new Error("Failed to bind test listener");
    }

    const baseUrl = `http://127.0.0.1:${address.port}`;
    const timeline = await fetch(`${baseUrl}/api/v1/consumer/orders/${orderId!}/timeline`);
    assert.equal(timeline.status, 200);
    const payload = (await timeline.json()) as { entries: unknown[] };
    assert.ok(payload.entries.length >= 3);
  } finally {
    listenerB.close();
  }
});

test("timeline rebuild rehydrates from durable outbox after restart", async () => {
  const documentStore = new InMemoryDocumentStore();

  const appA = createServer({
    enablePersistence: true,
    documentStore,
  });
  const listenerA = appA.listen(0);

  try {
    const address = listenerA.address();
    if (!address || typeof address === "string") {
      throw new Error("Failed to bind test listener");
    }

    const baseUrl = `http://127.0.0.1:${address.port}`;
    await createAndAdvanceOrder(baseUrl);
  } finally {
    listenerA.close();
  }

  const appB = createServer({
    enablePersistence: true,
    documentStore,
  });
  const listenerB = appB.listen(0);

  try {
    const address = listenerB.address();
    if (!address || typeof address === "string") {
      throw new Error("Failed to bind test listener");
    }

    const baseUrl = `http://127.0.0.1:${address.port}`;
    const rebuildResponse = await fetch(`${baseUrl}/internal/orders/timeline/rebuild`, {
      method: "POST",
    });

    assert.equal(rebuildResponse.status, 200);
    const rebuild = (await rebuildResponse.json()) as { entriesRebuilt: number };
    assert.ok(rebuild.entriesRebuilt >= 3);
  } finally {
    listenerB.close();
  }
});
